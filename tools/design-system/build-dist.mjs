// Builds the package form the Claude Design importer (/design-sync) reads:
// dist/index.js (ESM, dependencies external), dist/*.d.ts, and out/tokens.css.
import * as esbuild from "esbuild"
import { execSync } from "child_process"
import fs from "fs"

await esbuild.build({
  entryPoints: ["src/index.ts"], bundle: true, format: "esm", packages: "external",
  jsx: "automatic", target: "es2019", outfile: "dist/index.js",
})
execSync("tsc -p .", { stdio: "inherit" })

// tokens.css: the site's shadcn variables (raw HSL triplets) as full colours,
// light on :root, dark on .dark and [data-theme="dark"].
const src = fs.readFileSync("../../app/assets/styles/base/variables.css", "utf8")
const block = (sel) => {
  const start = src.indexOf(sel)
  const body = src.slice(src.indexOf("{", start) + 1, src.indexOf("}", start))
  return [...body.matchAll(/(--[\w-]+):\s*([\d.]+ [\d.]+% [\d.]+%);/g)].map(([, k, v]) => `  ${k}: hsl(${v});`)
}
const radius = src.match(/--radius:\s*([^;]+);/)[1]
const css = `/* Generated by build-dist.mjs from app/assets/styles/base/variables.css - do not edit */
:root {
  --radius: ${radius};
${block(":root,\n").join("\n")}
}
.dark, [data-theme="dark"] {
${block(".dark {").join("\n")}
  color-scheme: dark;
}
`
fs.mkdirSync("out", { recursive: true })
fs.writeFileSync("out/tokens.css", css)
console.log("dist/index.js, dist/*.d.ts, out/tokens.css")
